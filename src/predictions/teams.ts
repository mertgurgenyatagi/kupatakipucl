import { CLUB_BADGE_FILES } from "./clubBadgeSlugs";

export interface Team {
  id: string;
  name: string;
  /** A short, distinct code for width-constrained displays — the team
   *  table's compact columns (Mert: "abbreviate team names... you can even
   *  use three letters. I don't want to scroll horizontally"). Common
   *  broadcast-style codes where one exists (BVB, PSG, PSV, GS); otherwise
   *  a plain first-three-letters reading, hand-checked for no collisions
   *  (Real Betis vs Real Madrid, Slavia vs Slovan being the traps here). */
  shortName: string;
}

/**
 * Crest source: each team's own badge, under public/club-badges/ named for
 * the team id (see clubBadgeSlugs.ts, generated by
 * scripts/import-club-badges.mjs).
 *
 * This used to hash the id into a 29-badge pool, because the badges were
 * real but the team list was a placeholder: "just randomly assign them to
 * teams, since the whole team list will be totally replaced anyway." The
 * team list has now been replaced, so the assignment is a direct lookup and
 * every team shows its actual crest. teams.test.ts asserts the badge map
 * and TEAMS cover each other exactly, so a team added without a badge fails
 * the suite rather than rendering the shield placeholder in production.
 *
 * The extension is looked up rather than assumed: two source SVGs were far
 * too large to ship (Real Betis was a 6.5 MB wrapper around embedded
 * rasters, and the ranker draws all 36 crests at once) and are served as
 * WebP instead.
 */
export function teamCrestSrc(id: string): string {
  return `/club-badges/${CLUB_BADGE_FILES[id] ?? `${id}.svg`}`;
}

